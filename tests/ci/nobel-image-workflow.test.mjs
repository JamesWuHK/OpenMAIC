import fs from 'node:fs';
import assert from 'node:assert/strict';
import test from 'node:test';

test('image workflow is bounded, manual on the recovery branch, and contains no deployment authority', () => {
  const workflow = JSON.parse(fs.readFileSync(new URL('../../.github/workflows/learner-cloud-image.yml', import.meta.url)));
  assert.deepEqual(Object.keys(workflow.on).sort(), ['push', 'workflow_dispatch']);
  assert.deepEqual(workflow.on.push, {branches:['codex/nobel-runner-recovery-20261104'], paths:['.github/workflows/nobel-native-request.json']});
  const runner = workflow.on.workflow_dispatch.inputs.runner;
  assert.equal(runner.type, 'choice');
  assert.equal(runner.default, 'self-hosted');
  assert.deepEqual(runner.options, ['self-hosted', 'public-standard']);
  assert.deepEqual(workflow.permissions, {contents: 'read', actions: 'read'});
  const job = workflow.jobs.candidate;
  assert.match(job['runs-on'], /\["ubuntu-24.04"\]/);
  assert.match(job['runs-on'], /\["self-hosted","Linux","X64","openmaic","cloud-ci"\]/);
  assert(job.if.includes("inputs.runner != 'public-standard' || (github.event.repository.visibility == 'public' && github.event.repository.private == false)"));
  assert(!/large|windows|macos/.test(job['runs-on']));
  const builder = job.steps.find(step => step.id === 'builder');
  assert.match(builder.uses, /^docker\/setup-buildx-action@[0-9a-f]{40}$/);
  assert.equal(builder.with.use, false);
  assert.equal(builder.with.install, false);
  assert.match(builder.with['driver-opts'], /memory=5g/);
  assert.match(builder.with['driver-opts'], /cpu-quota=150000/);
  assert.equal(builder.with.cleanup, false);
  assert.equal(builder.with['cache-binary'], false);
  const scripts = job.steps.map(step => step.run || '').join('\n');
  assert.match(scripts, /nobel-resources.py capacity --after-install/);
  assert.match(scripts, /nobel-resources.py prompts/);
  assert.match(scripts, /nobel-resources.py cleanup/);
  assert.match(scripts, /nobel-resources.py builder-record/);
  assert.match(scripts, /nobel-resources.py builder-caps/);
  assert(!/secrets\.|docker\s+(prune|system\s+prune|push)|--with-deps|learner-candidate/.test(JSON.stringify(job)));
  assert(job.steps.some(step => step.if === 'always()' && step.run?.includes('nobel-resources.py cleanup')));
  const qa = workflow.jobs.native_qa;
  assert.equal(qa['runs-on'], 'ubuntu-24.04');
  assert(qa.if.includes("github.event.repository.visibility == 'public'"));
  assert(qa.if.includes('github.event.repository.private == false'));
  assert.equal(qa.env.QA_RELAY_TOKEN, '${{ secrets.NOBEL_QA_RELAY_TOKEN }}');
  assert(!/DEEPSEEK_API_KEY|OPENROUTER_API_KEY|SSH_PRIVATE|AWS_SECRET/.test(JSON.stringify(qa)));
  assert(job.if.startsWith("inputs.phase != 'native-qa'"));
  assert(job.if.includes("github.event_name == 'workflow_dispatch'"));
});
